#!/usr/bin/env python
"""Store the Twilio credentials (and the API key, when needed) in AWS.

    python scripts/put_secrets.py

Reads TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN, TWILIO_WHATSAPP_FROM, TWILIO_VOICE_FROM
(.env or the environment) and writes them as one JSON secret named TWILIO_SECRET_NAME
(default "ecolink/twilio"), which the Lambdas read at runtime. Values are never printed.

SECRETS_BACKEND (.env) chooses the store:
  secretsmanager (default)  AWS Secrets Manager. The API key is generated by the CDK stack.
  ssm                       SSM Parameter Store SecureString, for accounts where Secrets Manager
                            is blocked. CloudFormation cannot create encrypted parameters, so this
                            script also generates the API key (<prefix>/api-key) if it is missing.
"""

from __future__ import annotations

import json
import os
import re
import secrets as pysecrets
import sys
from typing import Any

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import envfile  # noqa: E402

FIELDS = {
    "account_sid": "TWILIO_ACCOUNT_SID",
    "auth_token": "TWILIO_AUTH_TOKEN",
    "whatsapp_from": "TWILIO_WHATSAPP_FROM",
    "voice_from": "TWILIO_VOICE_FROM",
}


def read_credentials(environ: dict[str, str]) -> dict[str, str]:
    missing = [var for var in FIELDS.values() if not environ.get(var)]
    if missing:
        raise SystemExit(f"Missing in .env / environment: {', '.join(missing)}")
    creds = {key: environ[var].strip() for key, var in FIELDS.items()}
    problems = []
    if not re.fullmatch(r"AC[0-9a-fA-F]{32}", creds["account_sid"]):
        problems.append("TWILIO_ACCOUNT_SID should look like AC + 32 hex characters")
    if not re.fullmatch(r"whatsapp:\+\d{8,15}", creds["whatsapp_from"]):
        problems.append("TWILIO_WHATSAPP_FROM should look like whatsapp:+14155238886")
    if not re.fullmatch(r"\+\d{8,15}", creds["voice_from"]):
        problems.append("TWILIO_VOICE_FROM should be E.164, e.g. +14155550100")
    if problems:
        raise SystemExit("\n".join(problems))
    return creds


def upsert_secret(client: Any, name: str, creds: dict[str, str]) -> str:
    """Secrets Manager: create the secret or add a new version; returns 'created' or 'updated'."""
    payload = json.dumps(creds)
    try:
        client.create_secret(Name=name, SecretString=payload, Description="EcoLink Twilio credentials")
        return "created"
    except client.exceptions.ResourceExistsException:
        client.put_secret_value(SecretId=name, SecretString=payload)
        return "updated"


def upsert_parameter(ssm: Any, name: str, value: str, *, overwrite: bool = True) -> str:
    """SSM: store a SecureString parameter; returns 'created', 'updated' or 'kept'."""
    param = "/" + name.lstrip("/")
    try:
        ssm.put_parameter(Name=param, Value=value, Type="SecureString", Description="EcoLink secret")
        return "created"
    except ssm.exceptions.ParameterAlreadyExists:
        if not overwrite:
            return "kept"
        ssm.put_parameter(Name=param, Value=value, Type="SecureString", Overwrite=True)
        return "updated"


def main() -> None:
    envfile.load_env()
    creds = read_credentials(dict(os.environ))
    name = os.environ.get("TWILIO_SECRET_NAME", "ecolink/twilio")
    region = os.environ.get("AWS_REGION") or os.environ.get("AWS_DEFAULT_REGION") or "ap-south-1"
    backend = os.environ.get("SECRETS_BACKEND", "secretsmanager").lower()
    tail = f"(account_sid=...{creds['account_sid'][-4:]})"

    import boto3

    if backend == "ssm":
        ssm = boto3.client("ssm", region_name=region)
        outcome = upsert_parameter(ssm, name, json.dumps(creds))
        print(f"{outcome} SecureString parameter '/{name.lstrip('/')}' in {region} {tail}")
        api_key_name = f"{os.environ.get('ECOLINK_PREFIX', 'EcoLink').lower()}/api-key"
        outcome = upsert_parameter(ssm, api_key_name, pysecrets.token_urlsafe(36), overwrite=False)
        print(f"{outcome} API key parameter '/{api_key_name}' (generated, never printed)")
    elif backend == "secretsmanager":
        outcome = upsert_secret(boto3.client("secretsmanager", region_name=region), name, creds)
        print(f"{outcome} secret '{name}' in {region} {tail}")
    else:
        raise SystemExit("SECRETS_BACKEND must be 'secretsmanager' or 'ssm'")


if __name__ == "__main__":
    main()
